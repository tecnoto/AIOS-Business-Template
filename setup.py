    banner()

    # --- Business Configuration ---
    print("Business Configuration:")
    business_name = ask("Business name")
    agent_name = ask("Agent name (the AI's identity)", default="Atlas")
    business_type = ask_choice(
        "Business type:",
        ["solo", "small", "mid-market", "enterprise"]
    )

    # --- User Configuration ---
    print("\nUser Configuration:")
    user_name = ask("Your name")
    user_email = ask("Email", required=False)
    telegram_user_id = ask("Telegram user ID (or 'skip')", required=False)
    if telegram_user_id.lower() == "skip":
        telegram_user_id = ""

    # --- Memory Configuration ---
    print("\nMemory Configuration:")
    mem0_user_id = ask("User ID for mem0", default=user_name.lower().split()[0])
    pinecone_index = ask(
        "Pinecone index name (or 'skip' for local-only)",
        default=f"{business_name.lower().replace(' ', '-')}-memory"
    )
    if pinecone_index.lower() == "skip":
        pinecone_index = ""

    # --- Environment Detection ---
    print("\nEnvironment Detection:")
    python_path = detect_python()
    print(f"  Python: {python_path}")
    claude_path = detect_claude()
    print(f"  Claude CLI: {claude_path}")
    ollama_available = check_ollama()
    print(f"  Ollama: {'available' if ollama_available else 'not detected'}")

    # --- API Keys ---
    print("\nAPI Keys (stored in .env — leave blank to skip):")
    anthropic_key = ask("ANTHROPIC_API_KEY", required=False, secret=True)
    openai_key = ask("OPENAI_API_KEY (for mem0)", required=False, secret=True)
