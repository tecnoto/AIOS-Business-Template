def create_plist(config):
    """Generate launchd plist for Telegram bot daemon."""
    project_path = str(PROJECT_ROOT)
    python_path = config["python_path"]
    agent_name = config["agent_name"].lower().replace(" ", "-")
    label = f"com.aios.{agent_name}-bot"

    plist = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>{label}</string>
    <key>ProgramArguments</key>
    <array>
        <string>{python_path}</string>
        <string>{project_path}/tools/telegram/bot_polling.py</string>
    </array>
    <key>WorkingDirectory</key>
    <string>{project_path}</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>PYTHONPATH</key>
        <string>{project_path}</string>
    </dict>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>StandardOutPath</key>
    <string>{project_path}/data/bot_stdout.log</string>
    <key>StandardErrorPath</key>
    <string>{project_path}/data/bot_stderr.log</string>
</dict>
</plist>"""

    plist_path = PROJECT_ROOT / "tools" / "telegram" / f"{agent_name}-bot.plist"
    plist_path.parent.mkdir(parents=True, exist_ok=True)
    plist_path.write_text(plist, encoding="utf-8")
    print(f"  Created: {plist_path}")


def init_databases(config):
    """Initialize SQLite databases with schema."""
    data_dir = PROJECT_ROOT / "data"
    data_dir.mkdir(exist_ok=True)

    # activity.db — tasks, events, messages
    conn = sqlite3.connect(str(data_dir / "activity.db"))
    conn.executescript("""
        CREATE TABLE IF NOT EXISTS tasks (
            id TEXT PRIMARY KEY,
            source TEXT,
            request TEXT,
            status TEXT DEFAULT 'pending',
            department TEXT DEFAULT 'general',
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            completed_at DATETIME,
            summary TEXT
        );

        CREATE TABLE IF NOT EXISTS telegram_events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            message_id TEXT UNIQUE,
            user_id TEXT NOT NULL,
            chat_id TEXT NOT NULL,
            message_text TEXT,
            intent TEXT,
            handler TEXT,
            response TEXT,
            department TEXT DEFAULT 'general',
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            processing_time_ms INTEGER
        );

        CREATE TABLE IF NOT EXISTS messages (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id TEXT NOT NULL,
            platform TEXT DEFAULT 'telegram',
            direction TEXT NOT NULL,
            content TEXT NOT NULL,
            intent TEXT,
            department TEXT DEFAULT 'general',
            metadata TEXT,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP
        );

        CREATE INDEX IF NOT EXISTS idx_messages_user_date
            ON messages(user_id, created_at DESC);
        CREATE INDEX IF NOT EXISTS idx_messages_department
            ON messages(department);
        CREATE INDEX IF NOT EXISTS idx_tasks_department
            ON tasks(department);
    """)
    conn.close()
    print("  Initialized: data/activity.db")

    # memory.db — local typed memory
    conn = sqlite3.connect(str(data_dir / "memory.db"))
    conn.executescript("""
        CREATE TABLE IF NOT EXISTS memory_entries (
            id INTEGER PRIMARY KEY,
            content TEXT NOT NULL,
            entry_type TEXT DEFAULT 'fact',
            importance INTEGER DEFAULT 5,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            source TEXT DEFAULT 'manual',
            embedding BLOB,
            embedding_model TEXT,
            updated_at DATETIME
        );
    """)
    conn.close()
    print("  Initialized: data/memory.db")


