def verify(config):
    """Run verification checks."""
    print("\n  Verification:")
    checks = [
        (".env exists", (PROJECT_ROOT / ".env").exists()),
        ("setup_config.yaml exists", (PROJECT_ROOT / "setup_config.yaml").exists()),
        ("settings.local.json exists", (PROJECT_ROOT / ".claude" / "settings.local.json").exists()),
        ("activity.db exists", (PROJECT_ROOT / "data" / "activity.db").exists()),
        ("memory.db exists", (PROJECT_ROOT / "data" / "memory.db").exists()),
        ("MEMORY.md exists", (PROJECT_ROOT / "memory" / "MEMORY.md").exists()),
    ]
    all_pass = True
    for label, passed in checks:
        status = "OK" if passed else "FAIL"
        print(f"    [{status}] {label}")
        if not passed:
            all_pass = False
    return all_pass


